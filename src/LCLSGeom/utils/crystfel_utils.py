"""
CrystFEL utility functions and group definitions for various detectors.
"""

from LCLSGeom.utils.detectors import get_family, get_layout

# Rayonix is a single monolithic panel: there is nothing to group, and .geom -> .data is not
# implemented for it.
NO_PANEL_GROUPS = ("Rayonix",)


def panel_names(detname):
    """
    CrystFEL panel names of a detector, one per psana segment, in segment order.

    Parameters
    ----------
    detname : str
        Detector name in psana (e.g., 'jungfrau4M', 'epix10k2M', etc.)

    Returns
    -------
    names : str
        Comma-separated panel names, or None if the detector has no panel decomposition
    """
    family = get_family(detname)
    if family in NO_PANEL_GROUPS:
        return None
    nsegs, _ = get_layout(family)
    # ponytail: the old hand-written table stopped at 16 panels for the 32-segment Jungfrau16M.
    # Kept here so this commit is a pure reorganization; fixed in the following commit.
    nsegs = min(nsegs, 16)
    return ','.join(f'p{n}a0' for n in range(nsegs))


def panel_groups(family):
    """
    Millepede group definitions of a detector: one group per segment, then one per quadrant.

    Quadrants are only emitted when the segments divide into four groups of at least two, which
    is what makes a quadrant a meaningful rigid body to refine.

    Parameters
    ----------
    family : str
        Detector family, as returned by get_family

    Returns
    -------
    groups : dict
        Group name to comma-separated members, empty if the detector has no groups
    """
    if family in NO_PANEL_GROUPS:
        return {}
    nsegs, nasics = get_layout(family)
    groups = {f'group_p{n}': ','.join(f'p{n}a{a}' for a in range(nasics))
              for n in range(nsegs)}

    per_quad = nsegs // 4
    if nsegs % 4 == 0 and per_quad >= 2:
        groups.update({f'group_q{q}': ','.join(f'p{n}' for n in range(q*per_quad, (q+1)*per_quad))
                       for q in range(4)})
        groups['group_all'] = 'q0,q1,q2,q3'
    return groups


def sfields_to_xyz_vector(flds):
    """
    Converts ['+0.002583x', '-0.999997y', '+0.000000z'] to (0.002583, -0.999997, 0.000000)

    A missing z field is read as 0.

    Parameters
    ----------
    flds : list
        List of strings representing x, y, and z coordinates
    """
    v = (float(flds[0].strip('x')), float(flds[1].strip('y')))
    z = float(flds[2].strip('z')) if len(flds)==3 else 0
    v += (z,)
    return v

def str_is_segment_and_asic(s):
    """
    Normalizes a CrystFEL panel name such as 'q0a2' or 'p12a7' to 'p0a2' or 'p12a7'

    Returns False if the string does not have that shape.

    Parameters
    ----------
    s : str
        Input string to check
    """
    if not isinstance(s, str)\
    or len(s)<2: return False
    flds = s[1:].split('a')
    return False if len(flds) !=2 else\
        'p%sa%s' % (flds[0], flds[1]) if all([f.isdigit() for f in flds]) else\
        False

def header_crystfel(distance):
    """
    Returns the header for the CrystFEL geometry file.
    The header includes the clen and photon energy PVs.

    Parameters
    ----------
    distance : float
        The distance from the source to the detector [m]
    """
    txt = (
        f'\n; Geometry Constants generated by LCLSGeom'
        f'\n'
        f'\nclen = {distance:f}'
        f'\nphoton_energy = /LCLS/photon_energy_eV'
        f'\nadu_per_eV = 0.1'
        f'\n'
        f'\ndata = /entry_1/data_1/data'
        f'\n'
        f'\ndim0 = %'
        f'\ndim1 = ss'
        f'\ndim2 = fs'
        f'\n'
        f'\n; mask = /entry_1/data_1/mask'
        f'\n; mask_good = 0x0000'
        f'\n; mask_bad = 0xffff'
    )
    return txt

def panel_crystfel(n, a, nfs, nss, x, y, z, pix_size, arows, acols, srows, nasicsf):
    """
    Returns the CrystFEL record for one ASIC panel.

    Parameters
    ----------
    n : int
        Segment index
    a : int
        ASIC index within the segment
    nfs, nss : np.ndarray
        Unit vectors along the fast and slow scan directions
    x, y, z : float
        Coordinates [um] of the first pixel of the ASIC
    pix_size : float
        Pixel size [um]
    arows, acols : int
        Number of rows and columns of the ASIC
    srows : int
        Number of rows of a segment
    nasicsf : int
        Number of ASICs along the fast scan direction
    """
    pref = '\np%da%d' % (n, a)
    return '%s/fs = %+.6fx %+.6fy %+.6fz' % (pref, nfs[0], nfs[1], nfs[2])\
        + '%s/ss = %+.6fx %+.6fy %+.6fz' % (pref, nss[0], nss[1], nss[2])\
        + '%s/res = %.3f' % (pref, 1e6/pix_size)\
        + '%s/corner_x = %.6f' % (pref, x/pix_size)\
        + '%s/corner_y = %.6f' % (pref, y/pix_size)\
        + '%s/coffset = %.6f' % (pref, z*1e-6)\
        + '%s/min_fs = %d' % (pref, (a%nasicsf)*acols)\
        + '%s/max_fs = %d' % (pref, (a%nasicsf+1)*acols-1)\
        + '%s/min_ss = %d' % (pref, n*srows + (a//nasicsf)*arows)\
        + '%s/max_ss = %d' % (pref, n*srows + (a//nasicsf+1)*arows - 1)\
        + '%s/no_index = 0' % (pref)\
        + '\n'

def tailer_crystfel(detname):
    """
    Returns the tailer for the CrystFEL geometry file.
    The tailer includes the panel and quadrant group definitions used by millepede.

    An unrecognized detector name yields no group definitions.

    Parameters
    ----------
    detname : str
        Detector family, as returned by get_family (e.g., 'Jungfrau16M', 'ePix10k2M', etc.)
    """
    lines = [f'{name} = {members}' for name, members in panel_groups(detname).items()]
    return '\n' + '\n'.join(lines)
